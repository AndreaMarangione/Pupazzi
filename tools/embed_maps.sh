#!/bin/sh
# Generates the C++ source with the maps embedded in the core, in campaign order.
#   sh tools/embed_maps.sh maps/terra1.txt ... > build/gen/maps_data.cpp
echo '// Generated by tools/embed_maps.sh: do not edit, change the files in maps/.'
echo '#include "game/sim/maps.h"'
echo 'const MapText MAP_TEXTS[] = {'
for f in "$@"; do
  id=$(basename "$f" .txt)
  printf '  { "%s",\n' "$id"
  sed -e 's/\r$//' -e 's/\\/\\\\/g' -e 's/"/\\"/g' -e 's/^/    "/' -e 's/$/\\n"/' "$f"
  printf '  },\n'
done
echo '};'
echo "const int MAP_TEXT_COUNT = $#;"
